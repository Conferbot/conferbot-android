#!/bin/sh
# Rebuild the widget languages (core/i18n/I18nStrings.kt and I18nGames.kt)
# from the React Native SDK's scripts/parity/i18n/strings.json, the table all
# SDKs share (the web's 824 keys from conferbot-widget ts/i18n/*.ts, plus the
# sdk.* words only the SDKs draw, in en/nl/fr/de/es, and the waiting games'
# quiz and word scramble per language). Run `node gen.js` in RN first when the
# widget or sdk-strings.json changed, then this, then commit the two files.
#
#   sh scripts/sync-i18n.sh          writes the Kotlin files
#   sh scripts/sync-i18n.sh --check  exits 1 when they are out of date
#
# CONFERBOT_DEV is the folder holding sdk/ (default: two levels up).
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
DEV="${CONFERBOT_DEV:-$(cd "$HERE/../../.." && pwd)}"
JSON="$DEV/sdk/conferbot-react-native/scripts/parity/i18n/strings.json"
OUT="$HERE/../conferbot/src/main/java/com/conferbot/sdk/core/i18n"
[ -f "$JSON" ] || { echo "not found: $JSON" >&2; exit 1; }
mkdir -p "$OUT"
node - "$JSON" "$OUT" "$1" <<'JS'
const fs = require('fs');
const path = require('path');
const [json, out, flag] = process.argv.slice(2);
const d = JSON.parse(fs.readFileSync(json, 'utf8'));
const LANGS = d.languages;
const keys = Object.keys(d.strings.en);
const sdk = new Set(d.sdkKeys);
// A Kotlin string literal: JSON escapes, with $ escaped for templates.
const q = (s) => JSON.stringify(s).replace(/\$/g, '\\$');
const cls = (l) => `I18n${l[0].toUpperCase()}${l.slice(1)}`;
const head = (what) => [
  'package com.conferbot.sdk.core.i18n',
  '',
  '/*',
  ` * ${what}`,
  " * Generated by scripts/sync-i18n.sh from the React Native SDK's",
  ' * scripts/parity/i18n/strings.json (conferbot-widget ts/i18n/<lang>.ts and',
  ' * sdk-strings.json). Do not edit; change the source and run the script.',
  ' */',
  '',
];
const s = head('The widget\'s own words in each language, by key.');
s.push(`/** Every key, the web's first (${keys.length - sdk.size}), then the SDK's own (sdk.*, ${sdk.size}). */`);
s.push('internal object I18nKeys {');
s.push('    val ALL: Array<String> = arrayOf(');
for (const k of keys) s.push(`        ${q(k)},`);
s.push('    )');
s.push('}');
for (const l of LANGS) {
  s.push('');
  s.push(`/** ${d.names[l]}: [I18nKeys.ALL]'s words, in its order (null: not translated). */`);
  s.push(`internal object ${cls(l)} {`);
  s.push('    val VALUES: Array<String?> = arrayOf(');
  for (const k of keys) s.push(`        ${typeof d.strings[l][k] === 'string' ? q(d.strings[l][k]) : 'null'},`);
  s.push('    )');
  s.push('}');
}
s.push('');
s.push('/** Each language\'s values, in I18n.SUPPORTED order. */');
s.push(`internal fun i18nValuesOf(lang: String): Array<String?> = when (lang) {`);
for (const l of LANGS.slice(1)) s.push(`    ${q(l)} -> ${cls(l)}.VALUES`);
s.push(`    else -> ${cls(LANGS[0])}.VALUES`);
s.push('}');
const g = head('The waiting games\' quiz and word scramble per language (web ts/chat/games/content.ts).');
g.push('import com.conferbot.sdk.core.waiting.GamesLogic.Trivia');
g.push('import com.conferbot.sdk.core.waiting.GamesLogic.Word');
g.push('');
g.push('internal object I18nGames {');
g.push('    fun triviaOf(lang: String): List<Trivia> = when (lang) {');
for (const l of LANGS.slice(1)) g.push(`        ${q(l)} -> TRIVIA_${l.toUpperCase()}`);
g.push(`        else -> TRIVIA_${LANGS[0].toUpperCase()}`);
g.push('    }');
g.push('');
g.push('    fun wordsOf(lang: String): List<Word> = when (lang) {');
for (const l of LANGS.slice(1)) g.push(`        ${q(l)} -> WORDS_${l.toUpperCase()}`);
g.push(`        else -> WORDS_${LANGS[0].toUpperCase()}`);
g.push('    }');
for (const l of LANGS) {
  g.push('');
  g.push(`    private val TRIVIA_${l.toUpperCase()}: List<Trivia> by lazy {`);
  g.push('        listOf(');
  for (const t of d.games.trivia[l]) g.push(`            Trivia(${q(t.q)}, ${q(t.a)}, listOf(${t.wrong.map(q).join(', ')})),`);
  g.push('        )');
  g.push('    }');
  g.push('');
  g.push(`    private val WORDS_${l.toUpperCase()}: List<Word> by lazy {`);
  g.push('        listOf(');
  for (const w of d.games.words[l]) g.push(`            Word(${q(w.w)}, ${q(w.hint)}),`);
  g.push('        )');
  g.push('    }');
}
g.push('}');
const files = { 'I18nStrings.kt': s.join('\n') + '\n', 'I18nGames.kt': g.join('\n') + '\n' };
let stale = 0;
for (const [name, text] of Object.entries(files)) {
  const f = path.join(out, name);
  const now = fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '';
  if (now === text) continue;
  stale++;
  if (flag === '--check') console.error(`out of date: ${name}`);
  else fs.writeFileSync(f, text);
}
console.log(`${keys.length} keys (${sdk.size} sdk.*) x ${LANGS.length} languages; ${flag === '--check' ? (stale ? `${stale} stale` : 'up to date') : `${stale} written`}`);
if (flag === '--check' && stale) process.exit(1);
JS
